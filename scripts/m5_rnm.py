"""M5: calibrate the SystemVerilog real-number sense-amp model against SPICE.

  1. SPICE: resolve time vs bitline split for the chosen sense amp (standard-Vt 2x)
  2. fit  t = T0 + TAU * ln(VSW / |dv|)   (latch regeneration), TMIN = enable-ramp floor
  3. write rnm/sa_params.svh, run the SV testbenches with Icarus Verilog
  4. compare RNM vs SPICE (decision + timing error) and the RNM yield run vs
     the SPICE Monte Carlo offset distribution

Outputs: results/m5_rnm_vs_spice.csv, results/m5_rnm_fit.txt, results/m5_yield.csv,
         plots/m5_rnm_vs_spice.png, plots/m5_rnm_yield.png
"""
import csv
import math
import os
import subprocess
import time
import numpy as np
import spice

RNM = os.path.join(spice.ROOT, "rnm")
VDD, VSW, T_EN = 1.8, 0.8 * 1.8, 0.2     # VSW = 80% of VDD, same as the DRAM tsense measure
SA = dict(wn=2.0, wp=4.0, lp=0.15)       # chosen design: standard-Vt latch, 2x wide


def spice_sweep():
    mags = np.logspace(np.log10(0.5e-3), np.log10(0.4), 22)
    dvs = np.concatenate([mags, -mags])
    b = [f"VDD vdd 0 {VDD}\n",
         f"VSAN san 0 PWL(0 0.9 {T_EN}n 0.9 {T_EN + 0.5}n 0)\n",
         f"VSAP sap 0 PWL(0 0.9 {T_EN + 0.5}n 0.9 {T_EN + 1.0}n {VDD})\n"]
    ic, meas = [], []
    for i, dv in enumerate(dvs):
        bl, blb = f"bl{i}", f"blb{i}"
        b.append(f"C{bl} {bl} 0 100f\nC{blb} {blb} 0 100f\n")
        b.append(spice.fet(f"n1_{i}", bl, blb, "san", "0", "n", SA["wn"], 0.15))
        b.append(spice.fet(f"n2_{i}", blb, bl, "san", "0", "n", SA["wn"], 0.15))
        b.append(spice.fet(f"p1_{i}", bl, blb, "sap", "vdd", "p", SA["wp"], SA["lp"]))
        b.append(spice.fet(f"p2_{i}", blb, bl, "sap", "vdd", "p", SA["wp"], SA["lp"]))
        ic.append(f"v({bl})={0.9 + dv / 2:.7f} v({blb})={0.9 - dv / 2:.7f}")
        meas.append(f"let d{i} = v({bl}) - v({blb})\nlet a{i} = abs(d{i})\n"
                    f"meas tran t{i} when a{i}={VSW} rise=1\n"
                    f"meas tran o{i} find d{i} at=9.9n")
    b.append(".ic " + " ".join(ic) + "\n")
    b.append(".control\ntran 5p 10n\n" + "\n".join(meas) + "\n.endc\n")
    t0 = time.time()
    r = spice.run("m5_sa_sweep", "".join(b))
    t_spice = time.time() - t0
    t = np.array([r.get(f"t{i}", np.nan) for i in range(len(dvs))]) * 1e9 - T_EN
    dec = np.array([1 if r.get(f"o{i}", 0) > 0 else 0 for i in range(len(dvs))])
    return dvs, t, dec, t_spice


def fit(dvs, t):
    a = np.abs(dvs)
    m = (a >= 1e-3) & (a <= 0.1) & np.isfinite(t)
    X = np.log(VSW / a[m])
    tau, t0 = np.polyfit(X, t[m], 1)
    tmin = float(np.nanmin(t))
    return float(t0), float(tau), tmin


def sigma_os():
    p = os.path.join(spice.RESULTS, "m4_sa_offset.csv")
    if not os.path.exists(p):
        return 0.0077, None
    off = np.array([float(r["offset_svt2x_V"]) for r in csv.DictReader(open(p))])
    return float(off.std(ddof=1)), off


def run_sv(t0, tau, tmin, sig, dvs):
    with open(os.path.join(RNM, "sa_params.svh"), "w") as f:
        f.write("// generated by scripts/m5_rnm.py from SPICE (do not edit)\n"
                f"`define SA_T0 {t0:.6f}\n`define SA_TAU {tau:.6f}\n"
                f"`define SA_VSW {VSW:.4f}\n`define SA_TMIN {tmin:.6f}\n"
                f"`define SA_SIGMA_OS {sig:.6f}\n`define SA_SEED 2026\n")
    with open(os.path.join(RNM, "dv_list.txt"), "w") as f:
        f.write("\n".join(f"{d:.7g}" for d in dvs) + "\n")
    times = {}
    for tb in ("tb_sa_sweep", "tb_sa_yield"):
        subprocess.run(["iverilog", "-g2012", "-o", f"{tb}.vvp", "dram_sa_rnm.sv", f"{tb}.sv"],
                       cwd=RNM, check=True)
        t = time.time()
        subprocess.run(["vvp", "-n", f"{tb}.vvp"], cwd=RNM, check=True, capture_output=True)
        times[tb] = time.time() - t
    return times


def main():
    plt = spice.style()
    dvs, t_sp, dec_sp, t_spice = spice_sweep()
    t0, tau, tmin = fit(dvs, t_sp)
    sig, off = sigma_os()
    times = run_sv(t0, tau, tmin, sig, dvs)
    rows = list(csv.DictReader(open(os.path.join(RNM, "rnm_sweep.csv"))))
    t_rnm = np.array([float(r["t_res_ns"]) for r in rows])
    dec_rnm = np.array([1 if r["decision"] == "1" else 0 for r in rows])
    err = t_rnm - t_sp
    a = np.abs(dvs)
    with open(f"{spice.RESULTS}/m5_rnm_vs_spice.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["dv_V", "spice_decision", "rnm_decision", "spice_t_ns", "rnm_t_ns", "error_ns"])
        for row in zip(dvs, dec_sp, dec_rnm, t_sp, t_rnm, err):
            w.writerow(row)
    band = (a >= 1e-3) & (a <= 0.1)
    summary = (f"T0 = {t0:.4f} ns\nTAU = {tau:.4f} ns\nTMIN = {tmin:.4f} ns\nVSW = {VSW:.3f} V\n"
               f"sigma_os (SPICE MC, standard-Vt 2x) = {sig*1e3:.2f} mV\n"
               f"decisions matching SPICE: {int((dec_sp == dec_rnm).sum())}/{len(dvs)}\n"
               f"timing error, 1-100 mV: max |err| = {np.nanmax(np.abs(err[band]))*1e3:.0f} ps, "
               f"rms = {np.sqrt(np.nanmean(err[band]**2))*1e3:.0f} ps\n"
               f"timing error, all points: max |err| = {np.nanmax(np.abs(err))*1e3:.0f} ps\n"
               f"runtime: SPICE {len(dvs)} sense amps = {t_spice:.2f} s; "
               f"RNM sweep = {times['tb_sa_sweep']:.2f} s; RNM 240k-read yield run = {times['tb_sa_yield']:.2f} s\n")
    open(f"{spice.RESULTS}/m5_rnm_fit.txt", "w").write(summary)
    print(summary)

    # --- RNM vs SPICE timing
    fig, (a1, a2) = plt.subplots(2, 1, figsize=(7, 5.6), sharex=True,
                                 gridspec_kw=dict(height_ratios=[2, 1]))
    pos = dvs > 0
    a1.semilogx(a[pos] * 1e3, t_sp[pos], "o", ms=5, color=spice.SERIES[0], label="SPICE, BL high")
    a1.semilogx(a[~pos] * 1e3, t_sp[~pos], "s", ms=5, mfc="none", color=spice.SERIES[0],
                label="SPICE, BL low")
    xx = np.logspace(np.log10(0.4), np.log10(500), 200)
    a1.semilogx(xx, np.maximum(tmin, t0 + tau * np.log(VSW / (xx * 1e-3))), color=spice.SERIES[1],
                label=f"RNM: {t0:.2f} + {tau:.3f}·ln({VSW:.2f} V/|ΔV|) ns, ≥ {tmin:.2f}")
    a1.set_ylabel("Resolve time after enable (ns)")
    a1.set_title("Sense-amp real-number model vs SPICE (tt, 27 °C)")
    a1.legend(fontsize=8, loc="upper right")
    a2.semilogx(a[pos] * 1e3, err[pos] * 1e3, "o", ms=5, color=spice.SERIES[1])
    a2.semilogx(a[~pos] * 1e3, err[~pos] * 1e3, "s", ms=5, mfc="none", color=spice.SERIES[1])
    a2.axhline(0, color=spice.INK2, lw=0.8)
    a2.set_xlabel("Bitline split |ΔV| at enable (mV)")
    a2.set_ylabel("RNM − SPICE (ps)")
    fig.tight_layout()
    spice.save(fig, "m5_rnm_vs_spice.png")
    plt.close(fig)

    # --- yield: RNM statistical run vs SPICE Monte Carlo offsets
    y = list(csv.DictReader(open(os.path.join(RNM, "rnm_yield.csv"))))
    ydv = np.array([float(r["dv_V"]) for r in y])
    yf = np.array([int(r["n_fail"]) / int(r["n_reads"]) for r in y])
    nreads = int(y[0]["n_reads"])
    fig, ax = plt.subplots(figsize=(7, 3.8))
    xx = np.linspace(0, 0.075, 200)
    phi = np.array([0.5 * math.erfc(v / (sig * math.sqrt(2))) for v in xx])
    ax.semilogy(xx * 1e3, phi, color=spice.INK2, ls=":", lw=1.2, label="Gaussian, σ from SPICE MC")
    ok = yf > 0
    ax.semilogy(ydv[ok] * 1e3, yf[ok], "o", ms=6, color=spice.SERIES[1],
                label=f"RNM testbench ({nreads:,} reads per point)")
    rows_y = [[d, f] for d, f in zip(ydv, yf)]
    if off is not None:
        emp = np.array([(off > d).mean() for d in ydv])
        okk = emp > 0
        ax.semilogy(ydv[okk] * 1e3, emp[okk], "s", ms=6, mfc="none", color=spice.SERIES[0],
                    label=f"SPICE Monte Carlo ({len(off)} sense amps)")
        rows_y = [[d, f, e] for d, f, e in zip(ydv, yf, emp)]
    ax.set_xlabel("Bitline signal ΔV (mV)")
    ax.set_ylabel("Probability of a wrong read")
    ax.set_title("Read-failure rate vs signal: RNM statistics match SPICE")
    ax.legend(fontsize=8, loc="lower left")
    ax.set_ylim(1e-5, 1)
    spice.save(fig, "m5_rnm_yield.png")
    plt.close(fig)
    with open(f"{spice.RESULTS}/m5_yield.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["dv_V", "rnm_fail_rate", "spice_mc_fail_rate"])
        w.writerows(rows_y)


if __name__ == "__main__":
    main()
