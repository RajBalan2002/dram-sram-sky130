"""Collect the headline numbers from results/*.csv into results/summary.md."""
import csv
import os
import spice

R = spice.RESULTS


def rows(name):
    p = os.path.join(R, name)
    return list(csv.DictReader(open(p))) if os.path.exists(p) else []


def f(x, scale=1, nd=1):
    try:
        v = float(x) * scale
    except (TypeError, ValueError):
        return "n/a"
    return "n/a" if v != v else f"{v:.{nd}f}"


def main():
    out = ["# Results summary (generated by scripts/summary.py)\n"]

    r = {x["case"]: x for x in rows("m1_read.csv")}
    if r:
        out += ["## M1: DRAM read, restore, precharge (tt, 27 °C, VDD 1.8 V, VPP 2.6 V)\n",
                "| | read 1 | read 0 |", "|---|---|---|",
                f"| bitline signal ΔV (mV) | {f(r['m1_read1']['dv_share'], 1e3)} | {f(r['m1_read0']['dv_share'], 1e3)} |",
                f"| sense time (ns) | {f(r['m1_read1']['tsense'], 1e9, 2)} | {f(r['m1_read0']['tsense'], 1e9, 2)} |",
                f"| cell after restore (V) | {f(r['m1_read1']['vsn_restored'], 1, 3)} | {f(r['m1_read0']['vsn_restored'], 1, 3)} |",
                f"| precharge time, PEQ at VPP (ps) | {f(r['m1_read1']['tprecharge'], 1e12, 0)} | {f(r['m1_read0']['tprecharge'], 1e12, 0)} |",
                f"| BL-BLB left after 3.9 ns, PEQ at VDD (mV) | {f(r['m1_read1_peqvdd']['dv_residual'], 1e3)} | {f(r['m1_read0_peqvdd']['dv_residual'], 1e3)} |",
                ""]
    w = {x["case"]: x for x in rows("m1_write.csv")}
    if w:
        out += [f"Write: 0 written in {f(w['m1_write0']['twrite'], 1e9, 2)} ns, read back ΔV "
                f"{f(w['m1_write0']['dv_readback'], 1e3)} mV; 1 written to {f(w['m1_write1']['vsn_written'], 1, 3)} V, "
                f"read back ΔV {f(w['m1_write1']['dv_readback'], 1e3)} mV.\n"]
    v = rows("m1_vpp_sweep.csv")
    if v:
        full = [x for x in v if float(x["vsn_restored"]) > 1.79]
        out += [f"Full '1' restore needs VPP ≥ {full[0]['vpp'] if full else 'n/a'} V.\n"]

    ret = rows("m2_retention.csv")
    if ret:
        out += ["## M2: retention (Cs 20 fF, fail when ΔV < 50 mV)\n",
                "| device | condition | 27 °C | 85 °C | 125 °C |", "|---|---|---|---|---|"]
        keys = []
        for x in ret:
            k = (x["device"], x["condition"])
            if k not in keys:
                keys.append(k)
        for k in keys:
            vals = {x["temp_C"]: float(x["retention_s"]) for x in ret if (x["device"], x["condition"]) == k}
            fmt = lambda s: f"{s*1e3:.3g} ms" if s < 1 else f"{s:.3g} s"
            out.append(f"| {k[0]} | {k[1]} | {fmt(vals['27'])} | {fmt(vals['85'])} | {fmt(vals['125'])} |")
        out.append("")
    wc = rows("m2_worst_case.csv")
    if wc:
        out += ["## M2: PVT corners (5 corners x −40/27/125 °C x VDD ±10%, read 1 and read 0)\n",
                "| sense amp | failed cases | min abs ΔV (mV) | max sense time (ns) |", "|---|---|---|---|"]
        for sa in ("svt", "svt2x", "lvt"):
            d = {x["metric"]: x for x in wc if x["sense_amp"] == sa}
            if not d:
                continue
            out.append(f"| {sa} | {d['failed cases']['corner']} | "
                       f"{f(abs(float(d['min |dv| read0']['dv_share'])), 1e3)} | "
                       f"{f(d['max tsense']['tsense'], 1e9, 2)} |")
        out.append("")

    s = rows("m3_sram_corners.csv")
    if s:
        tt = [x for x in s if x["corner"] == "tt" and x["temp_C"] == "27"][0]
        lo_r = min(s, key=lambda x: float(x["read_snm_V"]))
        lo_w = min(s, key=lambda x: float(x["write_margin_V"]))
        out += ["## M3: 6T SRAM (PD/PG/PU = 0.84/0.42/0.42 µm, L 0.15 µm, VDD 1.8 V)\n",
                f"tt 27 °C: hold SNM {f(tt['hold_snm_V'], 1e3, 0)} mV, read SNM {f(tt['read_snm_V'], 1e3, 0)} mV, "
                f"write margin {f(tt['write_margin_V'], 1e3, 0)} mV, read current {f(tt['iread_A'], 1e6, 0)} µA.  ",
                f"Worst read SNM {f(lo_r['read_snm_V'], 1e3, 0)} mV ({lo_r['corner']}, {lo_r['temp_C']} °C); "
                f"worst write margin {f(lo_w['write_margin_V'], 1e3, 0)} mV ({lo_w['corner']}, {lo_w['temp_C']} °C).\n"]

    mc = rows("m4_summary.csv")
    if mc:
        out += ["## M4: Monte Carlo\n", "| quantity | mean (mV) | sigma (mV) | mean−6σ or 6σ (mV) |",
                "|---|---|---|---|"]
        for x in mc:
            out.append(f"| {x['quantity']} | {x['mean_mV']} | {x['sigma_mV']} | {x['mean_minus_6sigma_mV']} |")
        out.append("")

    p = os.path.join(R, "m5_rnm_fit.txt")
    if os.path.exists(p):
        out += ["## M5: real-number model vs SPICE\n", "```", open(p).read().strip(), "```", ""]

    open(os.path.join(R, "summary.md"), "w").write("\n".join(out) + "\n")
    print("wrote results/summary.md")


if __name__ == "__main__":
    main()
